/** آیا فهرست‌های پایه ساخته شده‌اند؟ */
export async function hasDefaultLookups(): Promise<boolean> {
  const rows: any[] = await db().$queryRawUnsafe(`SELECT COUNT(*) c FROM "LookupItem" WHERE "type"='material'`);
  return Number(rows?.[0]?.c) > 0;
}

/**
 * ساخت فهرست‌های پیش‌فرض — idempotent.
 * ردیف تکراری ساخته نمی‌شود و ردیف غیرفعال‌شده توسط کاربر دوباره فعال نمی‌شود.
 */
export async function ensureDefaultLookups(): Promise<void> {
  const p = db();
  const put = async (type: string, rows: (string | number)[][]) => {
    const have: any[] = await p.$queryRawUnsafe(`SELECT "name" FROM "LookupItem" WHERE "type"=?`, type);
    const names = new Set(have.map((h) => String(h.name)));
    let order = names.size;
    for (const r of rows) {
      if (names.has(String(r[0]))) { order++; continue; }
      await p.$executeRawUnsafe(
        `INSERT INTO "LookupItem" ("type","name","extra","sortOrder","active") VALUES (?,?,?,?,1)`,
        type, r[0], (r[1] as string) || '', ++order,
      );
    }
  };
  await put('material', MATERIALS);
  await put('expense_category', EXPENSE_CATEGORIES);
  await put('payer', PAYERS);
  await put('receipt_source', RECEIPT_SOURCES);
  await put('contractor', CONTRACTORS);
  const mach: any[] = await p.$queryRawUnsafe(`SELECT COUNT(*) c FROM "Machinery"`);
  if (Number(mach?.[0]?.c) === 0) {
    for (const m of MACHINERY) {
      await p.$executeRawUnsafe(
        `INSERT INTO "Machinery" ("name","model","plateNo","count","status") VALUES (?,?,?,?,'active')`,
        m[0], m[1], m[2], m[3],
      );
    }
  }
  await p.$executeRawUnsafe(`INSERT INTO "Company" ("id") VALUES (1) ON CONFLICT("id") DO NOTHING`);
}

