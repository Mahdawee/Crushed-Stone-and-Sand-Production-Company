/**
 * مفاهیم مشترک دامنه — یک تعریف، همه‌جا.
 *
 * ## چرا این فایل لازم شد
 * دو ایراد کاربر:
 *   ۱) «بیانیه و پیش‌پرداخت یک مفهوم است؛ یکی را نگهدار و دیگری را حذف کن.»
 *   ۲) «"مربوط" در حقیقت همان شاخه مصرف است؛ این مفهوم جدید را در تمامی
 *      سیستم و برنامه پیاده کن.»
 *
 * قبلاً این مفاهیم به‌صورت **رشته‌ی فارسی پراکنده** در چند فایل تکرار شده
 * بودند (`'امانت'` در کوئری‌های مانده، در seed، در برچسب‌های UI). یک رشته‌ی
 * تکراری یعنی روزی یکی از آن‌ها عوض می‌شود و بقیه نه — و مانده‌ی حساب
 * مشتری بی‌سروصدا غلط می‌شود. حالا همه‌ی این‌ها از یک جا می‌آیند.
 *
 * ## مدل «مربوط» (شاخه‌ی مصرف)
 * «مربوط» یک **شاخه‌ی مصرف/مرکز هزینه** است: باربری، دمترک، اکستر، یا هر
 * طرف حساب دیگری که هزینه/کرایه به آن نسبت داده می‌شود. در بل فروش، کرایه
 * و «قیمت تمام‌شده» هر دو به همان شاخه می‌روند، پس سود واقعی همان شاخه
 * دیده می‌شود. در مصرف، «مربوط» طرف حساب سند است. در رسید، «مربوط»
 * منبعی است که پول از آن شاخه آمده و **از بدهی مشتری کم نمی‌شود**.
 */

