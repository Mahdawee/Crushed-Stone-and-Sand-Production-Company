/**
 * مشتری گذری (بدون حساب).
 *
 * درخواست کاربر: «یک مشتری گذری باید ایجاد کنی که اگر مشتری انتخاب نشود
 * به مشتری بدون حساب یا همان مشتری گذری معامله صورت بگیرد».
 *
 * ## چرا یک ردیف واقعی در جدول `Customer` و نه `customerId = null`
 *   ۱) ستون `Sale."customerId"` با کلید خارجی به `Customer` بسته است و
 *      `NOT NULL` است؛ مقدار خالی یعنی «بل یتیم» که در فهرست مشتریان
 *      دیده نمی‌شود و از گزارش‌ها می‌افتد.
 *   ۲) با یک ردیف واقعی، فروش گذری در همان یک جا (کارت حساب «مشتری گذری»)
 *      قابل مرور است — کاربر می‌تواند ببیند امروز چقدر فروش گذری داشته.
 *   ۳) «حساب» با پرچم `isWalkIn` کنترل می‌شود، نه با شناسه‌ی جادویی:
 *      هیچ کوئری‌ای `WHERE id = 1` نمی‌نویسد.
 *
 * این ردیف در فهرست مشتریان و در فهرست‌های کشویی فرم‌ها نمایش داده نمی‌شود
 * (وگرنه کاربر دو جای مختلف یک چیز را می‌بیند و اشتباه انتخاب می‌کند).
 */
export const WALK_IN_CODE = '000';
export const WALK_IN_NAME = 'مشتری گذری (بدون حساب)';

/** برچسب کوتاه برای ستون‌های فهرست/چاپ */
export const WALK_IN_SHORT = 'مشتری گذری';

/**
 * شرط SQL برای «مشتری حسابدار» (همه به‌جز گذری).
 * از یک تابع می‌آید تا هر کوئری که مشتریان را فهرست می‌کند همان حرف را بزند.
 */
export function realCustomerSql(alias = ''): string {
  const p = alias ? `${alias}.` : '';
  return `COALESCE(${p}"isWalkIn",0)=0`;
}

/** آیا این شناسه/ردیف مشتری گذری است؟ */
export function isWalkInCustomer(row: { isWalkIn?: unknown; code?: unknown } | null | undefined): boolean {
  if (!row) return false;
  return Number(row.isWalkIn) === 1 || String(row.code ?? '') === WALK_IN_CODE;
}
