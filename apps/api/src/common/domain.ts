export type ReceiptAllocation = (typeof RECEIPT_SOURCES)[number]['allocation'];

/** همه‌ی نام‌های معتبر منبع رسید */
export const RECEIPT_SOURCE_NAMES = RECEIPT_SOURCES.map((s) => s.name as string);

/**
 * نام‌های قدیمی/غلط‌نویسی که باید به نام رسمی تبدیل شوند.
 *
 * چرا نگاشت و نه حذف: کاربران ممکن است سال‌ها سند با «بیانه» یا
 * «پیش پرداخت» ثبت کرده باشند. اگر فقط نام رسمی را قبول کنیم، آن اسناد از
 * گزارش‌ها بی‌اثر می‌شوند. نگاشت، داده‌ی قدیمی را **بدون تغییر** معتبر
 * نگه می‌دارد.
 */
export const RECEIPT_SOURCE_ALIASES: Record<string, string> = {
  'بیانه': 'بیانیه',
  'بیانیه/پیش پرداخت': 'بیانیه',
  'بیانیه / پیش پرداخت': 'بیانیه',
  'پیش پرداخت': 'بیانیه',
  'پیش‌پرداخت': 'بیانیه',
  'پیش پرداخت مشتری': 'بیانیه',
  'پیش‌پرداخت مشتری': 'بیانیه',
  'مربوط ': 'مربوط',
  'شاخه مربوط': 'مربوط',
  'شاخه‌ی مربوط': 'مربوط',
};

/** نام رسمی یک منبع رسید (نام ناشناخته دست‌نخورده می‌ماند) */
export function canonicalReceiptSource(name: unknown): string {
  const raw = String(name ?? '').trim();
  if (!raw) return '';
  return RECEIPT_SOURCE_ALIASES[raw] || raw;
}

/**
 * تخصیص پول از روی نام منبع.
 *
 * نام ناشناخته → `credit`؛ چون رفتار تاریخی برنامه همین بود و تغییر
 * خاموشِ آن یعنی مانده‌های ثبت‌شده عوض شوند.
 */
export function allocationForSource(name: unknown): ReceiptAllocation {
  const n = canonicalReceiptSource(name);
  const found = RECEIPT_SOURCES.find((s) => s.name === n);
  return found ? found.allocation : 'credit';
}

/**
 * تخصیص‌هایی که مانده‌ی مشتری را کم می‌کنند.
 *
 * ⚠ این فهرست **همان رفتار تاریخی برنامه** است: تا امروز هر رسیدی که
 * منبعش «امانت» نبود از بدهی کم می‌شد. اگر «بیانیه» یا «مربوط» را از این
 * فهرست برداریم، مانده‌ی همه‌ی مشتریانی که چنین سندی دارند یک‌شبه عوض
 * می‌شود — بدون اینکه کسی سندی زده باشد. پس فقط «امانت» کم نمی‌کند.
 * («بیانیه» اعتبار مشتری است و در نخستین بل بعدی تسویه می‌شود؛ «مربوط»
 * پولی است که از شاخه‌ی مربوط آمده و بل مشتری را تسویه می‌کند.)
 */
export const DEBT_REDUCING_ALLOCATIONS: ReceiptAllocation[] = ['credit', 'advance', 'related'];

/** منابعی که مانده را کم نمی‌کنند (برای کوئری‌های SQL) */
export const NON_DEBT_SOURCE_NAMES = RECEIPT_SOURCES.filter((s) => s.allocation === 'deposit').map((s) => s.name as string);

/**
 * شرط SQL «این رسید از بدهی کم می‌کند»، از روی یک نام مستعار/ستون.
 *
 * چرا این‌جا و نه رشته‌ی دستی در کوئری: قبلاً در سه کوئری مانده، رشته‌ی
 * `<> 'امانت'` تکرار شده بود. یک بار که مفهوم عوض شود، یکی از آن‌ها
 * جا می‌ماند و مانده‌ی مشتری در یک صفحه با صفحه‌ی دیگر نمی‌خواند.
 */
export function receiptDebtSql(columnSql: string): string {
  const list = NON_DEBT_SOURCE_NAMES.map((n) => `'${n.replace(/'/g, "''")}'`).join(', ');
  return `COALESCE(${columnSql},'') NOT IN (${list || "''"})`;
}

/**
 * همه‌ی املاکی که به یک منبع اشاره می‌کنند (نام رسمی + نام‌های قدیمی).
 * برای فیلتر کوئری لازم است: فیلتر «بیانیه» باید رسیدهای «پیش پرداخت» و
 * «بیانه» را هم برگرداند، وگرنه سابقه‌ی قدیمی از گزارش‌ها غیب می‌شود.
 */
export function receiptSourceVariants(name: unknown): string[] {
  const canon = canonicalReceiptSource(name);
  const out = [String(name ?? '').trim(), canon].filter(Boolean);
  for (const [alias, target] of Object.entries(RECEIPT_SOURCE_ALIASES)) {
    if (target === canon) out.push(alias);
  }
  return out.filter((v, i, a) => a.indexOf(v) === i);
}

/** آیا این پول از بدهی مشتری کم می‌شود؟ (تنها جایی که این تصمیم گرفته می‌شود) */
export function reducesCustomerDebt(allocation: unknown, sourceName?: unknown): boolean {
  const a = String(allocation || '') || allocationForSource(sourceName);
  return DEBT_REDUCING_ALLOCATIONS.includes(a as ReceiptAllocation);
}

